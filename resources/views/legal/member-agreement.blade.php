<h2>Scope</h2>
<p>This Member Agreement governs participation in Vaytoven's Managed Listing Program for owners of points-based vacation property (the "Member Program"). It is an addendum to, not a replacement of, the Terms of Service and Chargeback Policy.</p>

<h2>Eligibility</h2>
<p>You must be the legal owner of, or hold an authorised use right in, the points or weeks you wish to enroll. You must be in good standing with your underlying vacation club (Marriott, Hilton, Disney, Wyndham, RCI, Interval, or other supported program). You attest that enrolling these points or weeks in a managed rental is permitted by your club's rules.</p>

<h2>Onboarding and quoting</h2>
<p>Within one business day of your enquiry, a Vaytoven specialist will contact you to confirm your program rules, audit eligible inventory, and quote your all-in payout. The quote is illustrative; actual payouts depend on guest demand, dates, and final inventory loaded at booking time.</p>

<h2>Listing under Vaytoven's escrow account</h2>
<p>Eligible weeks are listed and booked under Vaytoven's escrow account so guest payment, custodial holding, and payout flow to you (net of fees) all occur on Vaytoven infrastructure. This structure also keeps the booking compliant with your club's rental policy by interposing Vaytoven as the booking party.</p>

<h2>Fees</h2>
<p>The Managed Listing Program fee is a flat 12% of the booking total. Net payouts release to your bank account 24 hours after guest check-in, on the same schedule as standard hosts.</p>

<h2>Member control</h2>
<p>You retain full control of which weeks are enrolled in the program. You may keep, gift, or rent weeks at your discretion, on a per-year basis. Withdrawal of a week from the program does not affect bookings already confirmed against it.</p>

<h2>Compliance</h2>
<p>Vaytoven will not list weeks in violation of your club's rules. If your club's rental policy changes, we will pause enrollment of affected programs and contact you before any further action.</p>

<h2>Termination</h2>
<p>Either party may terminate this Agreement on 30 days' written notice. Bookings already confirmed will be honored to their conclusion; payouts continue per the original schedule.</p>
